class ProductShowcase {
  constructor() {
    this.grid = document.getElementById('catalog-grid');
    this.tabsContainer = document.getElementById('catalog-tabs');
    this.glider = document.getElementById('catalog-glider');
    this.currentCategory = 'all';

    if (this.grid && this.tabsContainer) {
      this.init();
    }
  }

  init() {
    this.renderTabs();
    this.renderProducts('all');
    this.setupEventListeners();

    // Position glider initially with font readiness support
    const activeTab = this.tabsContainer.querySelector('.catalog-tab.active');
    if (activeTab) {
      setTimeout(() => this.positionGlider(activeTab), 50);
      setTimeout(() => this.positionGlider(activeTab), 250);
      if (document.fonts && document.fonts.ready) {
        document.fonts.ready.then(() => this.positionGlider(activeTab));
      }
    }
  }

  positionGlider(tab) {
    if (!this.glider || !tab) return;
    this.glider.style.width = `${tab.offsetWidth}px`;
    this.glider.style.transform = `translateX(${tab.offsetLeft}px)`;
  }

  renderTabs() {
    const tabs = this.tabsContainer.querySelectorAll('.catalog-tab');
    tabs.forEach(tab => {
      tab.addEventListener('click', () => {
        tabs.forEach(t => t.classList.remove('active'));
        tab.classList.add('active');
        this.positionGlider(tab);
        this.currentCategory = tab.dataset.category;
        this.renderProducts(this.currentCategory);
        
        // Smoothly scroll active tab into view on small screens
        if (typeof tab.scrollIntoView === 'function') {
          tab.scrollIntoView({ behavior: 'smooth', block: 'nearest', inline: 'center' });
        }
      });
    });
  }

  renderProducts(category) {
    this.grid.classList.add('fade-out');

    setTimeout(() => {
      this.grid.innerHTML = '';
      
      const filtered = (category === 'all')
        ? MEDICAL_PRODUCTS 
        : MEDICAL_PRODUCTS.filter(p => {
            const cat = (p.category || '').toLowerCase();
            const target = category.toLowerCase();
            if (target === 'nephro' || target === 'nephrology') return cat.includes('nephro');
            if (target === 'lines' || target === 'accessories') return cat.includes('lines');
            if (target === 'onco' || target === 'oncology') return cat.includes('onco');
            if (target === 'critical') return cat.includes('critical');
            if (target === 'cardiac') return cat.includes('cardiac');
            if (target === 'infusion') return cat.includes('infusion');
            return cat === target;
          });

      if (filtered.length === 0) {
        this.grid.innerHTML = `<div style="grid-column: 1/-1; text-align: center; padding: var(--sp-12); color: var(--clr-text-dim);">No devices found in this category.</div>`;
        this.grid.classList.remove('fade-out');
        return;
      }

      filtered.forEach(p => {
        const card = document.createElement('div');
        card.className = 'product-card';
        card.setAttribute('data-id', p.id);
        card.setAttribute('data-reveal', 'up');
        card.style.cursor = 'pointer';

        const catName = p.categoryDisplay ? p.categoryDisplay.split('·')[0].trim() : p.category;
        const variantsHtml = (p.specs && p.specs.Variants)
          ? `<div class="product-card__variants"><span style="font-weight:700;color:#0F172A">Variants.</span> ${p.specs.Variants}</div>`
          : '';
        const imgPath = (p.image || '').replace(/^\//, '');

        card.innerHTML = `
          <span class="product-card__badge">${catName}</span>
          <div class="product-card__img-wrap">
            <img src="${imgPath}" alt="${p.title}" class="product-card__img" loading="lazy" onerror="this.onerror=null;this.src='images/medical-products.png'">
          </div>
          <h3 class="product-card__title">${p.title}</h3>
          <p class="product-card__desc">${p.description}</p>
          ${variantsHtml}
          <div class="product-card__specs">
            <span class="spec-tag spec-tag--class">Class B</span>
            <span class="spec-tag spec-tag--sterile">Sterile</span>
            <span class="spec-tag spec-tag--shelf">3-year shelf life</span>
            <span class="spec-tag spec-tag--brand">VIREXA</span>
          </div>
          <div style="margin-top:auto;width:100%">
            <a href="product.html?id=${p.id}" class="btn btn--primary btn--sm product-card__btn" style="width:100%;text-decoration:none;display:inline-flex;align-items:center;justify-content:center;gap:6px;font-weight:600">View Device Details &rarr;</a>
          </div>
        `;

        card.addEventListener('click', (e) => {
          if (!e.target.closest('a')) {
            window.location.href = `product.html?id=${p.id}`;
          }
        });
        this.grid.appendChild(card);
      });

      if (window.initScrollReveal) {
        window.initScrollReveal();
      }

      this.grid.classList.remove('fade-out');
    }, 200);
  }

  setupEventListeners() {
    window.addEventListener('resize', () => {
      const activeTab = this.tabsContainer.querySelector('.catalog-tab.active');
      this.positionGlider(activeTab);
    }, { passive: true });
  }
}

document.addEventListener('DOMContentLoaded', () => {
  new ProductShowcase();
});
